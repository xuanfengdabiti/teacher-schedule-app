"""Notifications, push-device registrations and delivery attempts.

The tables model the durable side of the notification loop.  This slice does
not call a push provider and does not run a delivery command: new attempts stay
``pending`` until B40 implements a real channel.  In-app notifications are the
source of truth and remain readable when delivery is disabled or unavailable.
"""

from __future__ import annotations

from django.conf import settings
from django.db import models
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from apps.academics.models import TeacherProfile
from apps.common.models import TimeStampedUUIDModel


class NotificationType(models.TextChoices):
    SCHEDULE_CHANGED = "schedule_changed", _("正式课表变更")
    RESCHEDULE_RESULT = "reschedule_result", _("调课结果")
    HANDOFF_RECEIVED = "handoff_received", _("收到教学交接")
    HANDOFF_ACKNOWLEDGED = "handoff_acknowledged", _("教学交接已确认")
    INQUIRY_RECEIVED = "inquiry_received", _("收到协查请求")
    INQUIRY_REPLIED = "inquiry_replied", _("协查收到回复")
    PLAN_BEHIND = "plan_behind", _("教学计划落后")


class Notification(TimeStampedUUIDModel):
    """One durable in-app message; the recipient/event-key pair is unique."""

    recipient = models.ForeignKey(
        TeacherProfile,
        on_delete=models.PROTECT,
        related_name="notifications",
        verbose_name=_("接收教师"),
    )
    type = models.CharField(_("消息类型"), max_length=32, choices=NotificationType.choices)
    object_type = models.CharField(_("对象类型"), max_length=32)
    object_id = models.UUIDField(_("对象 ID"), null=True, blank=True)
    title = models.CharField(_("标题"), max_length=200)
    body = models.TextField(_("正文"))
    event_key = models.CharField(
        _("事件键"),
        max_length=128,
        help_text="业务事件 ID + 接收人；同一事件重复处理不得重复建消息。",
    )
    read_at = models.DateTimeField(_("已读时间"), null=True, blank=True)

    class Meta:
        verbose_name = _("消息")
        verbose_name_plural = _("消息")
        ordering = ("-created_at", "-id")
        constraints = [
            models.UniqueConstraint(
                fields=["recipient", "event_key"],
                name="notif_recipient_event_uniq",
            ),
        ]
        indexes = [
            models.Index(fields=["recipient", "created_at"], name="notif_recip_created_idx"),
            models.Index(fields=["recipient", "read_at"], name="notif_recip_read_idx"),
        ]

    def __str__(self) -> str:
        return f"{self.recipient_id} {self.type}: {self.title}"


class DeviceProvider(models.TextChoices):
    GETUI = "getui", _("个推")
    APNS = "apns", _("APNs")


class DevicePlatform(models.TextChoices):
    ANDROID = "android", _("Android")
    IOS = "ios", _("iOS")


class DeviceRegistration(TimeStampedUUIDModel):
    """A client installation bound to one account at a time.

    ``installation_id`` is generated by the App and globally unique.  When a
    different account signs in on the same installation, the device row is
    transferred rather than duplicated; this is the only behaviour that lets
    one phone switch accounts without leaving pushes addressed to the old one.
    """

    installation_id = models.CharField(_("安装 ID"), max_length=255, unique=True)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="device_registrations",
        verbose_name=_("账号"),
    )
    provider = models.CharField(_("推送厂商"), max_length=16, choices=DeviceProvider.choices)
    provider_client_id = models.CharField(_("推送客户端 ID"), max_length=255, null=True, blank=True)
    platform = models.CharField(_("平台"), max_length=16, choices=DevicePlatform.choices)
    enabled = models.BooleanField(_("启用"), default=True)
    last_seen_at = models.DateTimeField(_("最后活跃时间"), default=timezone.now)

    class Meta:
        verbose_name = _("推送设备")
        verbose_name_plural = _("推送设备")
        ordering = ("-last_seen_at", "-id")
        indexes = [
            models.Index(fields=["user", "enabled"], name="notif_device_user_enabled_idx"),
        ]

    def __str__(self) -> str:
        return f"{self.installation_id} ({self.provider}/{self.platform})"


class DeliveryStatus(models.TextChoices):
    PENDING = "pending", _("待投递")
    PROCESSING = "processing", _("处理中")
    SENT = "sent", _("供应商已受理")
    FAILED = "failed", _("失败")


class DeliveryAttempt(TimeStampedUUIDModel):
    """One attempt target; sent means provider acceptance, not user read."""

    notification = models.ForeignKey(
        Notification,
        on_delete=models.PROTECT,
        related_name="delivery_attempts",
        verbose_name=_("消息"),
    )
    device = models.ForeignKey(
        DeviceRegistration,
        on_delete=models.PROTECT,
        related_name="delivery_attempts",
        verbose_name=_("设备"),
    )
    channel = models.CharField(_("通道"), max_length=16, choices=DeviceProvider.choices)
    attempt_no = models.PositiveIntegerField(_("尝试序号"), default=1)
    status = models.CharField(
        _("投递状态"),
        max_length=16,
        choices=DeliveryStatus.choices,
        default=DeliveryStatus.PENDING,
    )
    next_attempt_at = models.DateTimeField(_("下次尝试时间"), default=timezone.now)
    provider_message_id = models.CharField(_("供应商消息 ID"), max_length=255, blank=True, default="")
    provider_delivered_at = models.DateTimeField(_("设备回执时间"), null=True, blank=True)
    error_code = models.CharField(_("错误代码"), max_length=64, blank=True, default="")
    error_summary = models.TextField(_("错误摘要"), blank=True, default="")

    class Meta:
        verbose_name = _("投递记录")
        verbose_name_plural = _("投递记录")
        ordering = ("-created_at", "-id")
        constraints = [
            models.UniqueConstraint(
                fields=["notification", "device", "channel", "attempt_no"],
                name="notif_delivery_target_uniq",
            ),
        ]
        indexes = [
            models.Index(fields=["status", "next_attempt_at"], name="notif_delivery_status_next_idx"),
        ]

    def __str__(self) -> str:
        return f"{self.notification_id} -> {self.device_id} #{self.attempt_no} ({self.status})"
